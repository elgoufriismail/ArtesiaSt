const TEXTURE_MAP = { '6mcf62RlDfRfU61Yg5vb2pefpi4.png': 'noiseA → public/textures/noise-a.png', 'hfyi67pKwBIagdce3cECqq02Do.png': 'noiseB → public/textures/noise-b.png' };

// sections: built = directory has no data-stub marker
const secDir = `${ROOT}src/sections`;
const sections = Object.fromEntries(fs.readdirSync(secDir).map((d) => {
  const src = fs.readdirSync(path.join(secDir, d)).filter((f) => f.endsWith('.tsx')).map((f) => fs.readFileSync(path.join(secDir, d, f), 'utf8')).join('\n');
  return [d, { built: !/data-stub=""/.test(src), src }];
}));
// a slot is wired when it is referenced anywhere in src (sections or their content objects), except the
// registry itself, and its owning section is built
const srcFiles = (dir) => fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? srcFiles(path.join(dir, e.name)) : /\.(tsx?|css)$/.test(e.name) ? [path.join(dir, e.name)] : []));
const allSrc = srcFiles(`${ROOT}src`).filter((f) => !f.endsWith('content/assets.ts')).map((f) => fs.readFileSync(f, 'utf8')).join('\n');
const OWNER = Object.fromEntries(Object.values(MAP).filter(([slot]) => slot).map(([slot, owner]) => [slot, owner]));
const wiredIn = (slot) => {
  if (!(allSrc.includes(`'${slot}'`) || allSrc.includes(`"${slot}"`))) return [];
  return OWNER[slot].split(',').map((x) => x.trim()).filter((o) => sections[o]?.built);
};
const statusOf = (slot, owner) => {
  if (!slot) return 'excluded (not part of the design)';
  const w = wiredIn(slot);
  if (w.length) return `stand-in wired (${w.join(', ')})`;
  const owners = owner.split(',').map((x) => x.trim());
  return owners.some((o) => sections[o]?.built) ? 'stand-in exists, NOT wired' : 'stand-in exists (section not built yet)';
};
const rendered = (r) => (r ? Object.entries(r).map(([vp, [w, h]]) => `${w}×${h} @${vp.split('x')[0]}`).join('<br>') : '—');

const lines = [
  '# Asset ledger — original assets vs clone stand-ins',
  '',
  `Generated by \`tools/assets/ledger.mjs\` (${new Date().toISOString().slice(0, 10)}). Source of the original data:`,
  '`docs/reconnaissance/reference/assets/manifest.json`. Licensing: see ASSETS.md. Originals are **not** committed.',
  '',
  '**How to swap in licensed originals (per slot):** save the original file as `public/standins/<slot>.jpg`',
  '(same slot name, any resolution ≥ the original px size). Every component reads images through the',
  '`STANDINS` registry in `src/content/assets.ts`, which already carries the original pixel size and',
  'object-position, so layout and crops stay unchanged. Textures, masks and SVGs are listed with their target paths.',
  '',
  '## Photographs',
  '',
  '| Original file | Original px | Used in (original layer) | Rendered size | Fit / position | Clone slot | Status |',
  '|---|---|---|---|---|---|---|',
];
const counts = {};
for (const im of manifest.images) {
  const file = im.url.split('/').pop();
  const [slot, owner] = MAP[file] || [undefined, '?'];
  const st = slot === undefined ? 'UNMAPPED' : statusOf(slot, owner);
  counts[st.split(' (')[0]] = (counts[st.split(' (')[0]] || 0) + 1;
  lines.push(`| \`${file}\` | ${im.original.join('×')} | ${im.usedIn.join('<br>')} | ${rendered(im.renderedByViewport)} | ${im.objectFit || '—'} ${im.objectPosition || ''} | ${slot ? `\`${slot}\`` : '—'} | ${st} |`);
}
lines.push('', '## Tiled textures', '', '| Original file | px | CSS | Used in | Clone |', '|---|---|---|---|---|');
for (const t of manifest.tiledTextures) { const f = t.url.split('/').pop(); lines.push(`| \`${f}\` | ${t.original.join('×')} | ${t.css} | ${t.usedIn.join('<br>')} | ${TEXTURE_MAP[f] || '—'} (stand-in noise) |`); }
lines.push('', '## Masks', '', '| Original file | Intrinsic | Use | Clone |', '|---|---|---|---|');
for (const mk of manifest.masks) lines.push(`| \`${mk.url.split('/').pop()}\` | ${mk.intrinsic} | ${mk.use} | stand-in in \`public/masks/\` (see \`MASKS\`) |`);
lines.push('', '## Inline SVG / line art', '', '| Original | Detail | Clone |', '|---|---|---|');
// "How-It-Works long line": the two 680×2000 paths are children of the Big Quote section (measured Step 7) → built with Quote
for (const s of manifest.inlineSvg) lines.push(`| ${s.name} | ${[s.viewBox && `viewBox ${s.viewBox}`, s.render, s.stroke && `stroke ${s.stroke}`].filter(Boolean).join(' · ')} | stand-in paths (\`tools/standins/lines.mjs\` → \`src/components/decor/paths.ts\`) |`);
// section icons: inline data-URI SVG masks (64×64, green fill via background-color) — ASSETS.md §icons
const ICONS = [
  ['Philosophy', 'line-art seated figure (3 paths, bbox x 9–54, y 3–59 of 64)', 'public/icons/philosophy-standin.svg', 'Philosophy'],
  ['Pricing', 'waves (ink bbox x 7–57, y 15–50 of 64)', 'public/icons/pricing-standin.svg', 'Pricing'],
  ['Journal', 'lotus', null, 'Journal'],
];
lines.push('', '## Section icons (inline SVG masks, 64×64, #7fa69b fill)', '', '| Section | Original motif | Clone stand-in | Status |', '|---|---|---|---|');
for (const [sec, motif, file, owner] of ICONS) {
  const wired = file && fs.existsSync(`${ROOT}${file}`) && sections[owner]?.built && allSrc.includes(file.replace('public', ''));
  lines.push(`| ${sec} | ${motif} | ${file ? `\`${file}\` (different motif, same footprint/stroke)` : '—'} | ${wired ? 'stand-in wired' : file ? 'stand-in exists, NOT wired' : 'to be drawn with the section'} |`);
}
lines.push('', '## Fonts and icons', '', '| Original | Clone | Status |', '|---|---|---|');
