lines.push('| Avatar ring mask (`9O8sLldl6mV9miUVjkyrhGJsZ7c.svg`, mask-size contain, 0% 50%) | `public/masks/avatar-ring.svg` stand-in | stand-in wired (PathSection) |');
lines.push('', '## Summary', '', ...Object.entries(counts).map(([k, v]) => `* ${k}: ${v}`));
